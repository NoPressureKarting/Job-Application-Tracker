export const SAMPLE_JOB_IDS = new Set<string>(INITIAL_JOBS.map((j) => j.id));

export function isSampleJob(job: Partial<JobApplication> | null | undefined): boolean {
  if (!job) return false;
  if (job.id && SAMPLE_JOB_IDS.has(job.id)) return true;
  if (!job.company || !job.role) return false;
  const comp = job.company.trim().toLowerCase();
  const role = job.role.trim().toLowerCase();
  return INITIAL_JOBS.some(
    (sample) =>
      sample.company.toLowerCase() === comp &&
      sample.role.toLowerCase() === role
  );
}
